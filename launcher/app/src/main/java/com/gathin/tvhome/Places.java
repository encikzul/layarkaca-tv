        boolean valley = area[0].equals("Selangor") || area[0].equals("Wilayah Persekutuan");
        for (String[] s : STATIONS) {
            boolean same = valley ? s[0].equals("Selangor") || s[0].startsWith("WP ")
                    : s[0].equalsIgnoreCase(area[0]);
            if (same && !out.contains(s[1])) out.add(s[1]);
        }
        return out;
